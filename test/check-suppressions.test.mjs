function gitIn(root) {
  return (...args) => {
    const result = spawnSync("git", ["-c", "user.name=t", "-c", "user.email=t@t", ...args], { cwd: root, encoding: "utf8" });
    assert.equal(result.status, 0, result.stderr);
    return result.stdout;
  };
}

test("with no diff file, the CLI checks the diff since the base ref and untracked files", async () => {
  const root = await makeTree({ "src/a.js": "x();\n" });
  const git = gitIn(root);
  try {
    git("init", "-q", "-b", "main");
    git("add", ".");
    git("commit", "-q", "-m", "base");
    git("switch", "-q", "-c", "work");
    await writeFile(join(root, "src/a.js"), "x(); // eslint-disable-line\n");
    git("commit", "-q", "-am", "add a suppression");
    await writeFile(join(root, "src/new.py"), "import os  # noqa\n");
    const fail = run(["--base", "main", root]);
    assert.equal(fail.status, 1);
    assert.equal(fail.stderr, [blanket("src/a.js", 1, "eslint-disable"), blanket("src/new.py", 1, "noqa"), ""].join("\n"));
    // L7 in the review of #321: a root below the top level gives paths relative to the root.
    const sub = run(["--base", "main", join(root, "src")]);
    assert.equal(sub.stderr, [blanket("a.js", 1, "eslint-disable"), blanket("new.py", 1, "noqa"), ""].join("\n"));
    const badRef = run(["--base", "no-such-ref", root]);
    assert.equal(badRef.status, 2);
    assert.match(badRef.stderr, /^cannot read the diff: /);
  } finally {
    await removeTree(root);
  }
});

